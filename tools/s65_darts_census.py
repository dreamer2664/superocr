#!/usr/bin/env python3
"""S65 (t-20261014-138a): darts family deep-failure map on FRESH items.

Canonical seed-1 holds only 8 darts items, all at 0/8 (S43: 8 segmentation
misses). Real per-stage rates need fresh samples: this generates 40 items
with generator.py at seed >= 900 (never the canonical 1/2/3/4/53, never 7
— S6's diagnosis seed), reads them, and categorizes every failure by
stage with the same definitions the S6 stage diagnosis and the S43/S58
census tooling use:

  preclassify   the binarisation/polarity stage died: empty mask after
                otsu + despeck + trim (+ optional deskew) — the read was
                over before it started (S6's stage B, hard criterion)
  segmentation  mask has ink but the floor's own piece count (R.segment
                + split_wide + guards) != the true glyph count — collapsed,
                fused or split boxes (S6's stage S; S43's seg_piece proxy,
                here with split_wide rescue INCLUDED, so it is the floor's
                real piece structure, not the native pre-rescue count)
  classification pieces == true glyphs, mask healthy, and the produced
                string is still wrong — pure matcher loss (S6's stage C)

Primary category = earliest failing stage in that order; items are also
cross-tabbed with the S43 shipping-side decision tree on the FINAL read
(matching-case / segmentation / matching-glyph) and the token-aware lex
effect. Gallery = one example image per non-empty primary stage.

Gates (exit 1 on any FAIL): 40 items generated, all family darts, seed
>=900, generation is deterministic (index 0 re-generated byte-identical),
no canonical seed. Counts are measured, never assumed.

Usage:
  python3 tools/s65_darts_census.py [--seed 900] [--count 40] \
      --json reports/census-darts/2026-10-15.json \
      --jsonl reports/census-darts/2026-10-15-reads.jsonl \
      --gallery reports/census-darts/gallery
"""
from __future__ import annotations

import argparse
import hashlib
import io
import json
import sys
from collections import Counter
from pathlib import Path

import numpy as np
from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "tools"))

import baseline as B  # noqa: E402
import generator as G  # noqa: E402
import reader as R  # noqa: E402
from lex_projection import fix_line  # noqa: E402
from s58_miss_map import route_pieces  # noqa: E402  (S25 replication, shared)

try:
    from readers.segmentation import analyse as cnn_analyse  # noqa: E402
    CNN_OK = True
except Exception:  # pragma: no cover
    CNN_OK = False

CANONICAL_SEEDS = {1, 2, 3, 4, 53, 7}


def png_hash(img: Image.Image) -> str:
    buf = io.BytesIO()
    img.save(buf, format="PNG")
    return hashlib.sha256(buf.getvalue()).hexdigest()


# stage B + S helpers, byte-for-byte the S6 stage_diagnosis definitions
def baseline_mask(img: Image.Image) -> np.ndarray:
    """The floor's own binarisation path, up to (and incl.) deskew."""
    gray = ImageOps.autocontrast(img.convert("L"), cutoff=0)
    a = np.array(gray, dtype=np.float32)
    mask = R.trim(R.despeck(R.otsu(a)))
    if mask.any():
        mask, _ = B.deskew(mask)
        mask = R.trim(mask)
    return mask


def count_pieces(mask: np.ndarray) -> int:
    """The floor's own segmentation path (words, split_wide, guards)."""
    n = 0
    for word in R.segment(mask):
        for x0, x1 in word:
            for g in R.split_wide(R.trim(mask[:, x0:x1])):
                if g.shape[0] >= 6 and g.sum() >= 10:
                    n += 1
    return n


def lev(a: str, b: str) -> int:
    prev = list(range(len(b) + 1))
    for i, ca in enumerate(a, 1):
        cur = [i]
        for j, cb in enumerate(b, 1):
            cur.append(min(cur[-1] + 1, prev[j] + 1, prev[j - 1] + (ca != cb)))
        prev = cur
    return prev[-1]


def census(seed: int, count: int) -> list[dict]:
    rows = []
    for i in range(count):
        img, label = G.generate_one("darts", seed=seed, index=i)
        floor = B.read_text(img)[0]
        final = fix_line(floor)
        mask = baseline_mask(img)
        empty = not mask.any()
        ink = float(mask.mean())
        pieces = count_pieces(mask) if not empty else 0
        true = len(label.replace(" ", ""))
        words, wpieces = route_pieces(img)
        cnn_boxes = None
        if CNN_OK:
            _, boxes = cnn_analyse(img.convert("RGB"))
            cnn_boxes = len(boxes)
        # shipping-side S43 decision tree on the final read
        if final.lower() == label.lower():
            s43 = "matching-case"
        elif len(final) != len(label):
            s43 = "segmentation"
        else:
            s43 = "matching-glyph"
        # stage verdict: earliest failing stage
        if empty:
            stage = "preclassify"
        elif pieces != true:
            stage = "segmentation"
        elif floor != label:
            stage = "classification"
        else:
            stage = "exact-floor" if final != label else "exact"
        fd, xd = lev(floor, label), lev(final, label)
        from collections import Counter as _C
        tok_f = sum((_C(floor.split()) & _C(label.split())).values())
        tok_x = sum((_C(final.split()) & _C(label.split())).values())
        if tok_x > tok_f or (tok_x == tok_f and xd < fd):
            lex = "helped"
        elif tok_x < tok_f or (tok_x == tok_f and xd > fd):
            lex = "hurt"
        else:
            lex = "neutral"
        rows.append({
            "id": f"darts_{seed}_{i:03d}", "index": i, "seed": seed,
            "family": "darts", "label": label, "sha256": png_hash(img),
            "floor": floor, "final": final,
            "empty_mask": empty, "ink_frac": round(ink, 4),
            "pieces": pieces, "true_glyphs": true,
            "route_words": words, "route_pieces": wpieces,
            "cnn_boxes": cnn_boxes,
            "stage": stage, "s43_primary": s43,
            "lex": lex, "lev_floor": fd, "lev_final": xd,
            "exact_floor": floor == label, "exact_final": final == label})
    return rows


def summarize(rows: list[dict], seed: int) -> dict:
    misses = [r for r in rows if not r["exact_final"]]
    return {
        "seed": seed, "n": len(rows),
        "floor_exact": sum(r["exact_floor"] for r in rows),
        "final_exact": sum(r["exact_final"] for r in rows),
        "misses": len(misses),
        "stage": dict(Counter(r["stage"] for r in rows)),
        "stage_on_misses": dict(Counter(r["stage"] for r in misses)),
        "s43_primary_on_misses": dict(Counter(r["s43_primary"] for r in misses)),
        "lex_on_misses": dict(Counter(r["lex"] for r in misses)),
        "empty_mask_frac": round(sum(r["empty_mask"] for r in rows) / len(rows), 3),
        "mean_ink_frac": round(sum(r["ink_frac"] for r in rows) / len(rows), 4),
        "mean_pieces_per_true": round(
            sum(r["pieces"] for r in rows) / sum(r["true_glyphs"] for r in rows), 3),
        "mean_cnn_boxes_per_true": (
            round(sum(r["cnn_boxes"] or 0 for r in rows)
                  / sum(r["true_glyphs"] for r in rows), 3) if CNN_OK else None),
        "mean_lev_final_on_misses": (
            round(sum(r["lev_final"] for r in misses) / len(misses), 2)
            if misses else 0.0),
        "cnn_segmenter": CNN_OK,
        "manifest_sha256": hashlib.sha256(
            "".join(r["sha256"] for r in rows).encode()).hexdigest(),
    }


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--seed", type=int, default=900)
    ap.add_argument("--count", type=int, default=40)
    ap.add_argument("--json", type=Path)
    ap.add_argument("--jsonl", type=Path)
    ap.add_argument("--gallery", type=Path)
    a = ap.parse_args()

    gates, ok_all = [], True

    def gate(name: str, ok: bool, detail: str) -> None:
        nonlocal ok_all
        gates.append((name, ok, detail))
        ok_all &= ok

    gate("seed is non-canonical (>=900, never 1-4/53, never S6's 7)",
         a.seed >= 900 and a.seed not in CANONICAL_SEEDS, f"seed={a.seed}")

    rows = census(a.seed, a.count)
    s = summarize(rows, a.seed)

    gate("40 fresh darts items", s["n"] == a.count and all(
        r["family"] == "darts" for r in rows), f"n={s['n']}")
    img0a, lab0 = G.generate_one("darts", seed=a.seed, index=0)
    gate("generation deterministic", png_hash(img0a) == rows[0]["sha256"]
         and lab0 == rows[0]["label"], f"index0 sha {rows[0]['sha256'][:12]}…")

    print(f"darts fresh census — seed {a.seed}, n={s['n']}")
    print(f"floor exact {s['floor_exact']}/{s['n']} | "
          f"shipping (fix_line) exact {s['final_exact']}/{s['n']} | misses {s['misses']}")
    print(f"stage on all items: {s['stage']}")
    print(f"stage on misses:    {s['stage_on_misses']}")
    print(f"s43 primary on misses: {s['s43_primary_on_misses']}")
    print(f"lex on misses: {s['lex_on_misses']}")
    print(f"empty_mask {s['empty_mask_frac']} · mean ink {s['mean_ink_frac']} · "
          f"pieces/true {s['mean_pieces_per_true']} · cnn/true {s['mean_cnn_boxes_per_true']}")
    print(f"mean lev(final,label) on misses: {s['mean_lev_final_on_misses']}")
    print(f"manifest sha256: {s['manifest_sha256'][:16]}…")

    if a.gallery:
        a.gallery.mkdir(parents=True, exist_ok=True)
        kept = {}
        for r in rows:
            if r["exact_final"] or r["stage"] in kept:
                continue
            img, _ = G.generate_one("darts", seed=a.seed, index=r["index"])
            img.save(a.gallery / f"{r['id']}.png")
            kept[r["stage"]] = r["id"]
        print(f"gallery: {kept}")

    if a.jsonl:
        a.jsonl.parent.mkdir(parents=True, exist_ok=True)
        a.jsonl.write_text("\n".join(json.dumps(r) for r in rows) + "\n")
        print(f"wrote {a.jsonl}")
    if a.json:
        a.json.parent.mkdir(parents=True, exist_ok=True)
        a.json.write_text(json.dumps({"summary": s, "items": rows}, indent=1) + "\n")
        print(f"wrote {a.json}")

    print("\nGATES:")
    for name, ok, detail in gates:
        print(f"  {'PASS' if ok else 'FAIL'}  {name} — {detail}")
    print("VALIDATION:", "PASS" if ok_all else "FAIL")
    return 0 if ok_all else 1


if __name__ == "__main__":
    raise SystemExit(main())
